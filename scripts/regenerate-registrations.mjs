#!/usr/bin/env node
/**
 * Regenerates the two shared registration files from the module files present, so merges of
 * independently built modules never need manual conflict resolution:
 *   packages/db/src/schema/index.ts      (Database extends every module's *Tables interface)
 *   packages/contracts/src/api/index.ts  (re-exports every module's API contract file)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const schemaDir = path.join(root, 'packages/db/src/schema');
const schemaModules = readdirSync(schemaDir)
  .filter((f) => f.endsWith('.ts') && !['index.ts', 'core.ts'].includes(f))
  .sort()
  .map((f) => {
    const base = f.slice(0, -3);
    const match = /export interface (\w+Tables)\b/.exec(
      readFileSync(path.join(schemaDir, f), 'utf8'),
    );
    if (!match) throw new Error(`no *Tables interface exported from ${f}`);
    return { base, name: match[1] };
  });
const schemaLines = [
  "import type { CoreTables } from './core';",
  ...schemaModules.map((m) => `import type { ${m.name} } from './${m.base}';`),
  '',
  "export * from './core';",
  ...schemaModules.map((m) => `export * from './${m.base}';`),
  '',
  '/**',
  ' * The complete database type. Each module contributes its own table interfaces from',
  ' * `./<module>.ts`; run `node scripts/regenerate-registrations.mjs` after adding one.',
  ' */',
];
const extendsList = ['CoreTables', ...schemaModules.map((m) => m.name)].join(', ');
if (schemaModules.length === 0) {
  schemaLines.push(
    '// eslint-disable-next-line @typescript-eslint/no-empty-object-type -- extension point for module tables',
  );
}
schemaLines.push(`export interface Database extends ${extendsList} {}`, '');
writeFileSync(path.join(schemaDir, 'index.ts'), schemaLines.join('\n'));

const apiDir = path.join(root, 'packages/contracts/src/api');
const apiModules = readdirSync(apiDir)
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .sort()
  .map((f) => f.slice(0, -3));
writeFileSync(
  path.join(apiDir, 'index.ts'),
  [
    "// Each module's API contract file registers its paths with the shared OpenAPI registry on import.",
    '// Generated by scripts/regenerate-registrations.mjs; one line per module keeps merges conflict-free.',
    ...apiModules.map((m) => `export * from './${m}';`),
    '',
  ].join('\n'),
);
console.warn(`schema modules: ${schemaModules.map((m) => m.base).join(', ')}`);
console.warn(`api modules: ${apiModules.join(', ')}`);
