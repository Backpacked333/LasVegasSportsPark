/**
 * Metric registry (SPK-REPORT-001): every metric a report computes, with the nine SPK-REPORT-001
 * fields (numerator and denominator kept apart). Keys and wording follow
 * docs/package-a/metric-dictionary.md (MET-###), adjusted to state exactly what this code
 * computes. The registry seeds `metric_definitions` per organization; a changed entry produces a
 * new definition version (its hash changes) and supersedes the old one, so stored report runs keep
 * citing the version they were produced under (SPK-REPORT-007).
 *
 * Access scope names the action that must be held to view the metric (organization scope G1 and
 * facility scope G2 always apply). Freshness is the class of a live evaluation: every report reads
 * the owning modules' records at request time (F1); a stored report run is a snapshot (F3).
 */
export interface MetricSpec {
  key: string;
  name: string;
  reports: readonly ReportKey[];
  businessQuestion: string;
  grain: string;
  numerator: string;
  denominator: string;
  timeBasis: string;
  exclusions: readonly string[];
  dimensions: readonly string[];
  currency: 'none' | 'minor_units';
  freshness: FreshnessClass;
  accessScope: string;
  unit: MetricUnitValue;
  requirementIds: readonly string[];
  pendingDecisions?: readonly string[];
}

