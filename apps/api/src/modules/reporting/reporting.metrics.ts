const BY_KEY = new Map(METRICS.map((m) => [m.key, m]));

export function metricSpec(key: string): MetricSpec {
  const spec = BY_KEY.get(key);
  if (!spec) throw new Error(`unknown metric ${key}`);
  return spec;
}

export function metricsForReport(report: ReportKey): MetricSpec[] {
  return METRICS.filter((m) => m.reports.includes(report));
}

/** Stable SHA-256 over every definition field: a changed field is a new definition version. */
export function definitionHash(spec: MetricSpec): string {
  const canonical = JSON.stringify([
    spec.key,
    spec.name,
    [...spec.reports],
    spec.businessQuestion,
    spec.grain,
    spec.numerator,
    spec.denominator,
    spec.timeBasis,
    [...spec.exclusions],
    [...spec.dimensions],
    spec.currency,
    spec.freshness,
    spec.accessScope,
    spec.unit,
    [...spec.requirementIds],
    [...(spec.pendingDecisions ?? [])],
  ]);
  return createHash('sha256').update(canonical, 'utf8').digest('hex');
}
