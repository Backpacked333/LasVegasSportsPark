/**
 * Regenerates `src/generated/paths.ts` from `docs/api/openapi.json` (spec §4.8: "Publish exact
 * schemas in OpenAPI before client integration").
 *
 *   pnpm --filter @sportspark/api-client generate
 *
 * `src/__tests__/paths-current.spec.ts` renders the same output in memory and fails when the
 * committed file differs, so a changed API contract cannot reach the clients unnoticed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';

const here = path.dirname(fileURLToPath(import.meta.url));

export const OPENAPI_DOCUMENT = path.resolve(here, '../../../docs/api/openapi.json');
export const GENERATED_PATHS = path.resolve(here, '../src/generated/paths.ts');

const BANNER = [
  '/**',
  ' * Generated by `pnpm --filter @sportspark/api-client generate` from docs/api/openapi.json.',
  ' * Do not edit by hand: change the API, regenerate the OpenAPI document (`pnpm openapi`), then',
  ' * regenerate this file. `paths-current.spec.ts` fails when it is stale.',
  ' */',
  '',
].join('\n');

/** Renders the TypeScript declarations for the current OpenAPI document. */
export async function renderPaths(documentPath: string = OPENAPI_DOCUMENT): Promise<string> {
  const document = JSON.parse(readFileSync(documentPath, 'utf8')) as OpenAPI3;
  // `alphabetize` keeps the output stable when the emitter reorders paths or schemas.
  const ast = await openapiTS(document, {
    alphabetize: true,
    exportType: true,
  });
  return `${BANNER}${astToString(ast)}`;
}

async function main(): Promise<void> {
  const output = await renderPaths();
  writeFileSync(GENERATED_PATHS, output);
  console.warn(`Wrote ${path.relative(process.cwd(), GENERATED_PATHS)}`);
}

const invokedDirectly =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
}
